function Pipeline({ events }: { events: Ev[] }) {
  const last = (agents: string[]) => {
    for (let i = events.length - 1; i >= 0; i--) if (agents.includes(events[i].agent)) return events[i];
  };
  return (
    <section aria-label="Pipeline" className="scroll-thin overflow-x-auto rounded-xl border border-line bg-panel p-3">
      <ol className="grid min-w-[880px] grid-cols-8 gap-2">
        {STAGES.map((s, i) => {
          const e = last(s.agents);
          const t = tone(e?.state);
          return (
            <li key={s.key} className={`rounded-lg border bg-bg/50 p-2.5 transition-colors ${BORDER[t]}`}>
              <div className="flex items-center gap-1.5">
                <span className={`h-1.5 w-1.5 rounded-full ${DOT[t]}`} />
                <span className="font-mono text-[10px] text-dim">{String(i + 1).padStart(2, "0")}</span>
              </div>
              <div className="mt-1 text-[13px] font-semibold">{s.label}</div>
              <div className="text-[11px] text-dim">{s.sub}</div>
              <div className="mt-2 line-clamp-3 min-h-[3.2em] text-[11px] leading-snug text-mute" title={e?.msg}>{e?.msg || "—"}</div>
            </li>
          );
        })}
      </ol>
    </section>
  );
}

function Activity({ events }: { events: Ev[] }) {
  const ref = useRef<HTMLOListElement>(null);
  useEffect(() => { ref.current?.scrollTo({ top: 0 }); }, [events.length]);
  if (!events.length) return <Empty>Agent steps stream here.</Empty>;
  return (
    <ol ref={ref} className="scroll-thin max-h-[380px] space-y-2 overflow-y-auto pr-1">
      {[...events].reverse().map((e, i) => (
        <li key={i} className="flex gap-2.5 text-[12px] leading-snug">
          <span className={`mt-1.5 h-1.5 w-1.5 shrink-0 rounded-full ${DOT[tone(e.state)].replace(" pulse", "")}`} />
          <div className="min-w-0">
            <span className="font-mono text-[11px] text-dim">{e.t.toFixed(0)}s · {e.agent}</span>
            <div className={tone(e.state) === "bad" ? "text-bad" : "text-ink/90"}>{e.msg}</div>
          </div>
        </li>
      ))}
    </ol>
  );
}

